# -*- coding:utf-8 -*-
"""从 click 命令树机械导出命令元数据。

两类消费方：
- ``python -m dp_cli.catalog --md``  → 生成 commands.md 风格的命令表
- ``python -m dp_cli.catalog``       → 输出 MCP 风格 tool schema JSON
  （未来 mcp-serve 薄壳的上游；schema 由代码生成，不手写，不腐化）

文档腐化守卫见 tests/test_docs.py：commands.md 必须覆盖全部注册命令。
"""
from __future__ import annotations

import argparse
import json
import sys

import click

from dp_cli.main import cli

# 模块名 → 命令表类别（按模块机械归类，新增模块时在此补一行）
CATEGORY = {
    'browser': '浏览器', 'misc': '导航/页面', 'snapshot_cmd': '快照',
    'element': '提取/交互', 'keyboard': '键盘/滚动', 'network': '网络',
    'assert_cmd': '断言', 'emulate': '模拟/下载/拦截', 'observe': '观测',
    'tab': '标签页', 'storage': '存储', 'record': '录制',
    'page': '页面', 'batch': '批量',
}


def _param_schema(p):
    """click.Param → JSON Schema 片段。"""
    if isinstance(p, click.Option) and p.is_flag:
        t = {'type': 'boolean'}
    elif isinstance(p.type, click.types.IntParamType):
        t = {'type': 'integer'}
    elif isinstance(p.type, click.types.FloatParamType):
        t = {'type': 'number'}
    elif isinstance(p.type, click.types.BoolParamType):
        t = {'type': 'boolean'}
    elif isinstance(p.type, click.types.Choice):
        t = {'type': 'string', 'enum': list(p.type.choices)}
    else:
        t = {'type': 'string'}
    if getattr(p, 'multiple', False):
        t = {'type': 'array', 'items': t}
    if getattr(p, 'help', None):
        t['description'] = p.help
    return t


def iter_commands():
    """yield (name, help, input_schema) —— MCP tool 风格。"""
    for name in sorted(cli.commands):
        cmd = cli.commands[name]
        props, required = {}, []
        for p in cmd.params:
            props[p.name] = _param_schema(p)
            if p.required:
                required.append(p.name)
        yield {
            'name': name,
            'description': (cmd.help or '').strip().splitlines()[0] if cmd.help else '',
            'inputSchema': {'type': 'object', 'properties': props,
                            'required': required},
            '_category': CATEGORY.get(
                getattr(cmd.callback, '__module__', '').rsplit('.', 1)[-1],
                '其他'),
        }


def to_markdown(cmds):
    """生成按类别分组的 markdown 表（含 options 摘要）。"""
    by_cat = {}
    for c in cmds:
        by_cat.setdefault(c['_category'], []).append(c)
    lines = ['<!-- GENERATED by `python -m dp_cli.catalog --md` —— 勿手改 -->',
             '', '| 类别 | 命令 | 参数 |', '|------|------|------|']
    for cat in CATEGORY.values():
        for c in by_cat.pop(cat, []):
            params = ', '.join(
                (f'<{k}>' if k in c['inputSchema']['required'] else f'[{k}]')
                for k in c['inputSchema']['properties'])
            lines.append(f"| {cat} | `{c['name']}` | {params} |")
    for cat, cs in sorted(by_cat.items()):
        for c in cs:
            params = ', '.join(c['inputSchema']['properties'])
            lines.append(f"| {cat} | `{c['name']}` | {params} |")
    return '\n'.join(lines) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(prog='dp-cli-catalog')
    ap.add_argument('--md', action='store_true', help='输出 markdown 命令表')
    args = ap.parse_args(argv)
    cmds = list(iter_commands())
    if args.md:
        sys.stdout.write(to_markdown(cmds))
    else:
        tools = [{k: v for k, v in c.items() if not k.startswith('_')}
                 for c in cmds]
        json.dump({'tools': tools}, sys.stdout, ensure_ascii=False, indent=2)
        sys.stdout.write('\n')


if __name__ == '__main__':
    main()
