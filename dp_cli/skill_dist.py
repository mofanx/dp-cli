# -*- coding:utf-8 -*-
"""skill 随包分发：bundled 副本定位 / 版本戳 / 漂移检测 / 安装。

canonical 源是 repo 根 ``skills/dp-cli/``；wheel 构建期由 setup.py
build_py 复制为包内 ``dp_cli/skill/``。运行时优先读包内副本，
源码树 / editable 安装回退 repo 路径。
"""
from __future__ import annotations

import re
from pathlib import Path

_PKG_DIR = Path(__file__).resolve().parent
_VERSION_KEY = 'dp_cli_version'
_SKILL_NAME = 'dp-cli'

# 已知 agent harness 的 skill 根目录（对齐 Devin/Windsurf 官方搜索路径
# 与 Claude Code/agents 约定）。规则：harness 根目录存在 → 安装目标
# = <root>/skills/dp-cli；不存在不创建（避免给未装 harness 的用户留
# 无用目录）。AGENTS.md 是指令文件而非 skill 目录，不在此列。
_PROJ_ROOTS = ('.claude', '.agents', '.devin', '.windsurf',
               '.cursor', '.opencode')
_USER_ROOTS = ('.claude', '.agents', '.cursor', '.codex',
               '.config/devin', '.config/opencode')


def _all_roots(home=None, cwd=None):
    """(项目级, 用户级) harness 根目录——install --all 与 drift 扫描共用。"""
    home = home or Path.home()
    cwd = cwd or Path.cwd()
    return ([cwd / r for r in _PROJ_ROOTS],
            [home / r for r in _USER_ROOTS])


def existing_targets(home=None, cwd=None):
    """已存在 harness 根对应的安装目标 <root>/skills/dp-cli。

    去重：cwd==home（在 HOME 下运行）时同一根会同时命中项目级
    与用户级名单。"""
    proj, user = _all_roots(home, cwd)
    seen, out = set(), []
    for r in proj + user:
        t = r / 'skills' / _SKILL_NAME
        if r.is_dir() and t not in seen:
            seen.add(t)
            out.append(t)
    return out


def installed_copies(home=None, cwd=None):
    """已安装的 skill 副本 → {target_dir: 版本戳|None}（drift 扫描）。"""
    copies = {}
    for t in existing_targets(home, cwd):
        md = t / 'SKILL.md'
        if md.is_file():
            copies[t] = skill_version_of(md)
    return copies


def bundled_skill_dir():
    """bundled skill 目录；未找到返回 None。"""
    pkg = _PKG_DIR / 'skill'                                  # wheel 安装
    if pkg.is_dir():
        return pkg
    repo = _PKG_DIR.parent / 'skills' / 'dp-cli'              # 源码树/editable
    return repo if repo.is_dir() else None


def cli_version():
    try:
        from importlib.metadata import version
        return version('dp-cli')
    except Exception:
        return '0.0.0+unknown'


def skill_version_of(skill_md: Path):
    """SKILL.md frontmatter 的 dp_cli_version；无字段/无文件 → None。"""
    try:
        head = skill_md.read_text(encoding='utf-8', errors='replace')[:2000]
    except OSError:
        return None
    m = re.search(rf'^{_VERSION_KEY}:\s*"?([^"\s]+)"?\s*$', head, re.M)
    return m.group(1) if m else None


def _stamp_version(text: str, ver: str) -> str:
    """frontmatter 注入/更新 dp_cli_version。"""
    if re.search(rf'^{_VERSION_KEY}:', text, re.M):
        return re.sub(rf'^{_VERSION_KEY}:.*$',
                      f'{_VERSION_KEY}: {ver}', text,
                      count=1, flags=re.M)
    m = re.match(r'^---\n(.*?\n)---\n', text, re.S)
    if m:
        fm = m.group(1) + f'{_VERSION_KEY}: {ver}\n'
        return '---\n' + fm + '---\n' + text[m.end():]
    return f'---\n{_VERSION_KEY}: {ver}\n---\n\n' + text


def _refresh_commands_md(dst_dir: Path):
    """安装时现场重生成 references/commands.md 的 GENERATED 段——
    版本对齐由构造保证（catalog 源于运行时代码，非构建期快照）。"""
    cmd_md = dst_dir / 'references' / 'commands.md'
    if not cmd_md.is_file():
        return
    src = cmd_md.read_text(encoding='utf-8', errors='replace')
    marker = src.find('<!-- GENERATED by')
    if marker == -1:
        return
    from dp_cli.catalog import iter_commands, to_markdown
    cmd_md.write_text(src[:marker] + to_markdown(list(iter_commands())),
                      encoding='utf-8')


def install_skill(dst: Path):
    """幂等重写安装 skill 到 dst（目标目录本身整个替换）。"""
    import shutil
    src = bundled_skill_dir()
    if src is None:
        raise FileNotFoundError('包内未找到 bundled skill')
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(src, dst)
    _refresh_commands_md(dst)
    md = dst / 'SKILL.md'
    md.write_text(_stamp_version(md.read_text(encoding='utf-8', errors='replace'),
                                 cli_version()), encoding='utf-8')


def _normalize(rel: Path, text: str) -> str:
    """归一化差异源：SKILL.md 去版本戳行；commands.md 只留 GENERATED 前的
    手写头（生成段安装时由 catalog 现场重建，与 bundled 快照可能不同）。"""
    if rel.name == 'SKILL.md':
        return re.sub(rf'^{_VERSION_KEY}:.*\n', '', text, flags=re.M)
    if rel.name == 'commands.md':
        return text.split('<!-- GENERATED by')[0]
    return text


def skill_dirs_equal(src: Path, dst: Path):
    """bundled vs installed 内容比对——忽略版本戳与 commands.md 生成段。"""
    if not src.is_dir() or not dst.is_dir():
        return False
    s_files = {p.relative_to(src) for p in src.rglob('*') if p.is_file()}
    d_files = {p.relative_to(dst) for p in dst.rglob('*') if p.is_file()}
    if s_files != d_files:
        return False
    for rel in s_files:
        s = _normalize(rel, (src / rel).read_text(encoding='utf-8', errors='replace'))
        d = _normalize(rel, (dst / rel).read_text(encoding='utf-8', errors='replace'))
        if s != d:
            return False
    return True


def dir_diff_files(src: Path, dst: Path) -> list:
    """bundled vs installed 归一化内容差异文件清单（含多余/缺失）。"""
    diffs = []
    if not src.is_dir() or not dst.is_dir():
        return ['<dir missing>']
    s_files = {p.relative_to(src) for p in src.rglob('*') if p.is_file()}
    d_files = {p.relative_to(dst) for p in dst.rglob('*') if p.is_file()}
    diffs += [f'+{p}' for p in sorted(d_files - s_files)]   # installed 多余
    diffs += [f'-{p}' for p in sorted(s_files - d_files)]   # installed 缺失
    for rel in sorted(s_files & d_files):
        s = _normalize(rel, (src / rel).read_text(encoding='utf-8', errors='replace'))
        d = _normalize(rel, (dst / rel).read_text(encoding='utf-8', errors='replace'))
        if s != d:
            diffs.append(str(rel))
    return diffs


def check_drift(home=None, cwd=None):
    """版本戳 + 内容双检。返回 ({target: ver}, cur_ver, drift, {target: diffs})。

    drift = 任一副本版本戳≠CLI 或 归一化内容不一致（版本相同内容过期
    也报——改名批场景）。diffs 为差异文件清单（空 dict=无内容差）。"""
    copies = installed_copies(home, cwd)
    cur = cli_version()
    src = bundled_skill_dir()
    diffs = {}
    if src is not None:
        for t in copies:
            d = dir_diff_files(src, t)
            if d:
                diffs[t] = d
    drift = any(v != cur for v in copies.values()) or bool(diffs)
    return copies, cur, drift, diffs


_AGENTS_MD_BLOCK = """<!-- dp-cli-skill -->
## dp-cli（浏览器自动化 CLI）

本项目可用 `dp`（dp-cli）驱动浏览器：截图/快照/表单/录制/网络监听，
全部命令输出 JSON。实时命令表 `dpx catalog --md`；完整用法文档
`dpx install --skills` 安装到 agent skill 目录后见 SKILL.md。
定位优先 `pw:role=...`/`text:` 语义定位器，css 仅兜底。
<!-- /dp-cli-skill -->"""

_AGENTS_MD_RE = re.compile(
    r'<!-- dp-cli-skill -->.*?<!-- /dp-cli-skill -->', re.S)


def update_agents_md(path: Path) -> str:
    """AGENTS.md 注入/更新 dp-cli 指针段。返回 'created'|'updated'|'unchanged'。"""
    if path.is_file():
        text = path.read_text(encoding='utf-8', errors='replace')
        if _AGENTS_MD_RE.search(text):
            new = _AGENTS_MD_RE.sub(_AGENTS_MD_BLOCK, text)
            if new == text:
                return 'unchanged'
            path.write_text(new, encoding='utf-8')
            return 'updated'
        sep = '' if text.endswith('\n\n') or not text else '\n\n'
        path.write_text(text + sep + _AGENTS_MD_BLOCK + '\n',
                        encoding='utf-8')
        return 'updated'
    path.write_text(
        '# AGENTS.md\n\n' + _AGENTS_MD_BLOCK + '\n', encoding='utf-8')
    return 'created'


def warn_drift():
    """入口处 stderr 单行漂移警告——缺失静默、once-per-version 防刷屏、
    绝不碰 stdout、try/except 零干扰。扫描全部已知 harness 目标。"""
    try:
        copies, cur, drift, diffs = check_drift()
        if not drift:
            return
        stale = sorted({str(t) for t, v in copies.items() if v != cur}
                       | {str(t) for t in diffs})
        import hashlib
        sig = hashlib.sha1(
            f'{"|".join(stale)}|{cur}'.encode()).hexdigest()[:12]
        marker = Path.home() / '.dp_cli' / f'skill-warned-{sig}'
        if marker.exists():
            return
        marker.parent.mkdir(parents=True, exist_ok=True)
        marker.touch()
        import click
        shown = '、'.join(stale[:3]) + (' 等' if len(stale) > 3 else '')
        click.echo(f'[dp-cli] skill 漂移 @ {shown} ≠ CLI {cur}'
                   f'，运行 `dpx install --skills` 更新', err=True)
    except Exception:
        pass
