# -*- coding:utf-8 -*-
"""文档腐化守卫：skills/dp-cli/references/commands.md 必须覆盖全部注册命令。

新增命令未入文档时本测试失败——防止手写文档与 click 命令树脱节。
通配写法 `foo-*` 视为覆盖所有 `foo-` 前缀命令（如 localstorage-*）。
"""
import filecmp
import os
import re
import subprocess
import warnings
from pathlib import Path

import pytest

from dp_cli.main import cli

_COMMANDS_MD = (Path(__file__).parent.parent
                / 'skills' / 'dp-cli' / 'references' / 'commands.md')


def _documented_commands():
    md = _COMMANDS_MD.read_text(encoding='utf-8')
    tokens = re.findall(r'`([a-z][a-z0-9*-]+)`', md)
    doc = set()
    for t in tokens:
        if t.endswith('*'):
            doc.update(c for c in cli.commands if c.startswith(t[:-1]))
        elif t in cli.commands:
            doc.add(t)
    return doc


def test_all_commands_documented():
    missing = set(cli.commands) - _documented_commands()
    assert not missing, (
        f'commands.md 未覆盖 {len(missing)} 个命令: {sorted(missing)}\n'
        f'请在 {_COMMANDS_MD.name} 命令一览表中补充（或用 `prefix-*` 通配）')


def test_commands_md_freshness():
    """生成段必须与 catalog --md 输出一致——堵住只加选项忘记重生成的腐化路径。"""
    from dp_cli.catalog import iter_commands, to_markdown
    src = _COMMANDS_MD.read_text(encoding='utf-8')
    marker = src.find('<!-- GENERATED by')
    assert marker != -1, 'commands.md 缺少 GENERATED 标记段'
    expected = to_markdown(list(iter_commands()))
    actual = src[marker:]
    if actual.rstrip() != expected.rstrip():
        for i, (a, e) in enumerate(
                zip(actual.splitlines(), expected.splitlines())):
            if a != e:
                raise AssertionError(
                    f'commands.md 生成段第 {i + 1} 行起不一致:\n'
                    f'  文件: {a!r}\n  应为: {e!r}\n'
                    f'请重跑 python -m dp_cli.catalog --md 更新生成段')
        raise AssertionError(
            'commands.md 生成段长度不一致，请重跑 '
            'python -m dp_cli.catalog --md 更新生成段')


_SKILL_MD = _COMMANDS_MD.parent.parent / 'SKILL.md'
# SKILL.md 中允许引用但非真实命令的 token（兼容 `prefix-*` 通配）
# install/catalog：分发链命令，由独立任务实现，文档先行引用
_SKILL_CMD_WHITELIST = {'install', 'catalog'}


def _skill_referenced_commands():
    src = _SKILL_MD.read_text(encoding='utf-8')
    # 只扫代码段（围栏块 + 行内反引号）——prose 里的 dp/-V/skill 字样不算命令引用
    snippets = re.findall(r'```[\s\S]*?```|`[^`\n]+`', src)
    text = '\n'.join(snippets)
    # `dpx <opts> <cmd>` / `dp <cmd>` / `dp-cli <cmd>`（兼容写法仍合法），
    # 水平空白限定不跨行；前导选项按 `-x <值>` 成对跳过
    names = re.findall(
        r'\b(?:dpx|dp-cli|dp)[ \t]+(?:-{1,2}\S+[ \t]+\S+[ \t]+)*'
        r'([a-z][a-z0-9-]*)', text)
    allowed = {w[:-1] for w in _SKILL_CMD_WHITELIST if w.endswith('*')}
    return {n for n in names
            if n not in _SKILL_CMD_WHITELIST
            and not any(n.startswith(p) for p in allowed)}


def test_skill_md_command_references():
    """SKILL.md 引用的 `dp xxx` 命令名必须真实存在——防文档引用幽灵命令。"""
    bad = sorted(n for n in _skill_referenced_commands()
                 if n not in cli.commands)
    assert not bad, (
        f'SKILL.md 引用了 {len(bad)} 个不存在的命令: {bad}\n'
        f'请修正引用，或确属占位写法时加入 _SKILL_CMD_WHITELIST')


def test_catalog_schema_export():
    """catalog 导出：全部命令可机械转为 tool schema（MCP 上游能力）。"""
    from dp_cli.catalog import iter_commands
    tools = list(iter_commands())
    names = [t['name'] for t in tools]
    assert len(names) == len(cli.commands)
    assert len(set(names)) == len(names)
    for t in tools:
        assert t['inputSchema']['type'] == 'object'
        for req in t['inputSchema']['required']:
            assert req in t['inputSchema']['properties']


_REPO_ROOT = Path(__file__).parent.parent
_SKILL_SRC = _REPO_ROOT / 'skills' / 'dp-cli'
_SYNC_SH = _REPO_ROOT / 'scripts' / 'sync-skill.sh'


def test_skill_home_copy_sync_status():
    """~/.claude/skills/dp-cli 与 repo 副本一致性（软检查，不 hard fail）。

    无 ~/.claude 的环境（CI）跳过；本地漂移只 warnings.warn——
    提醒跑 scripts/sync-skill.sh，不阻断流水线。
    """
    dst = Path.home() / '.claude' / 'skills' / 'dp-cli'
    if not dst.is_dir():
        pytest.skip('~/.claude/skills/dp-cli 不存在（CI/无安装环境）')

    def _files(root: Path):
        return {p.relative_to(root) for p in root.rglob('*') if p.is_file()}

    only_src = _files(_SKILL_SRC) - _files(dst)
    only_dst = _files(dst) - _files(_SKILL_SRC)

    def _cmp(rel):
        a, b = _SKILL_SRC / rel, dst / rel
        if rel.name == 'SKILL.md':
            # installed 副本的 dp_cli_version 是安装时写入的真版本戳，
            # repo 副本是 "dev" 占位——归一化该行再比
            strip = lambda t: re.sub(r'^dp_cli_version:.*$', '',
                                     t, flags=re.M)
            return strip(a.read_text('utf-8')) == strip(b.read_text('utf-8'))
        return filecmp.cmp(a, b, shallow=False)

    differ = [str(r) for r in (_files(_SKILL_SRC) & _files(dst))
              if not _cmp(r)]
    if only_src or only_dst or differ:
        warnings.warn(
            f'skill 副本漂移：missing={sorted(map(str, only_src))} '
            f'extra={sorted(map(str, only_dst))} differ={sorted(differ)} '
            f'→ 运行 scripts/sync-skill.sh', UserWarning)


@pytest.mark.unit
def test_sync_skill_check_mode(tmp_path):
    """sync-skill.sh --check：DP_SKILL_DST 覆盖下的一致性判定。

    不同步真实 ~/.claude，只验证脚本契约：不一致→exit 1，同步后→exit 0。
    """
    env = {**os.environ, 'DP_SKILL_DST': str(tmp_path / 'skill')}
    dst = tmp_path / 'skill'
    r = subprocess.run(['bash', str(_SYNC_SH), '--check'],
                       env=env, capture_output=True, text=True)
    # dst 不存在 → SKIP exit 0（CI 安全）
    assert r.returncode == 0 and 'SKIP' in r.stdout

    # 不完整副本 → 漂移 exit 1
    dst.mkdir()
    (dst / 'SKILL.md').write_text('stale', encoding='utf-8')
    r = subprocess.run(['bash', str(_SYNC_SH), '--check'],
                       env=env, capture_output=True, text=True)
    assert r.returncode == 1 and 'OUT OF SYNC' in r.stderr

    # 同步后 → IN SYNC exit 0
    r = subprocess.run(['bash', str(_SYNC_SH)],
                       env=env, capture_output=True, text=True)
    assert r.returncode == 0 and 'SYNCED & VERIFIED' in r.stdout
    r = subprocess.run(['bash', str(_SYNC_SH), '--check'],
                       env=env, capture_output=True, text=True)
    assert r.returncode == 0 and 'IN SYNC' in r.stdout


@pytest.mark.unit
def test_plugin_manifest_version_sync():
    """marketplace.json / plugin.json 的 version 必须与 pyproject 一致——
    发版 bump 忘改时此处 fail（发版 checklist 的机器守卫）。"""
    import json
    pkg_ver = re.search(r'^version\s*=\s*"([^"]+)"',
                        (_REPO_ROOT / 'pyproject.toml')
                        .read_text(encoding='utf-8'), re.M).group(1)
    plugin = json.loads((_REPO_ROOT / '.claude-plugin' / 'plugin.json')
                        .read_text(encoding='utf-8'))
    market = json.loads((_REPO_ROOT / '.claude-plugin' / 'marketplace.json')
                        .read_text(encoding='utf-8'))
    assert plugin['version'] == pkg_ver, \
        f"plugin.json version {plugin['version']} ≠ pyproject {pkg_ver}"
    versions = {p['version'] for p in market['plugins']}
    assert versions == {pkg_ver}, \
        f'marketplace plugins version {versions} ≠ pyproject {pkg_ver}'


def test_error_codes_documented():
    """ERROR_CODES.md 必须覆盖 output.ERROR_CODES 全部错误码（支持 `PREFIX_*` 通配）。"""
    from dp_cli.output import ERROR_CODES
    md = (_REPO_ROOT / 'ERROR_CODES.md').read_text(encoding='utf-8')
    tokens = set(re.findall(r'`([A-Z][A-Z0-9*_]+)`', md))
    # 通配展开：`*` 可出现在任意位置（如 `RECORD_*_FAILED`）
    from fnmatch import fnmatch
    documented = {c for c in ERROR_CODES
                  if any(fnmatch(c, t) for t in tokens)}
    missing = sorted(set(ERROR_CODES) - documented)
    assert not missing, (
        f'ERROR_CODES.md 未覆盖 {len(missing)} 个错误码: {missing}\n'
        f'请在 ERROR_CODES.md 补充（或用 `PREFIX_*` 通配）')


@pytest.mark.unit
def test_skill_frontmatter_schema():
    """SKILL.md frontmatter：name/description 必需，值须 YAML 可解析。"""
    src = _SKILL_MD.read_text(encoding='utf-8')
    m = re.match(r'^---\n(.*?)\n---\n', src, re.S)
    assert m, 'SKILL.md 缺 frontmatter'
    fm = m.group(1)
    assert re.search(r'^name:\s*\S', fm, re.M)
    assert re.search(r'^description:\s*\S', fm, re.M)
    try:
        import yaml
        d = yaml.safe_load(fm)
        assert isinstance(d.get('allowed-tools'), str)
        assert isinstance(d.get('dp_cli_version'), str)
    except ImportError:
        pytest.skip('pyyaml 不可用')
